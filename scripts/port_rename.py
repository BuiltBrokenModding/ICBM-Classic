def rewrite_imports(src):
    out = []
    seen = set()
    for line in src.split('\n'):
        m = re.match(r'^import (static )?([\w.]+?)(\.\*)?;\s*$', line)
        if m and (m.group(2).startswith('net.minecraft') or m.group(2).startswith('net.minecraftforge')):
            static, name, star = m.group(1) or '', m.group(2), m.group(3) or ''
            if static:
                # static imports: map the owning class
                owner, member = name.rsplit('.', 1)
                if owner in IMPORTS:
                    new_owner = IMPORTS[owner]
                    if new_owner is None:
                        continue
                    line = 'import static %s.%s;' % (new_owner, member)
            elif star:
                line = '// PORT-TODO: wildcard import ' + name + '.* needs manual mapping'
            elif name in IMPORTS:
                new = IMPORTS[name]
                if new is None:
                    continue
                line = 'import %s;' % new
            if line in seen:
                continue
            seen.add(line)
        out.append(line)
    return '\n'.join(out)


def rewrite_code(src):
    # split off import block so types renames don't hit the already mapped imports
    lines = src.split('\n')
    body_start = 0
    for i, l in enumerate(lines):
        if l.startswith('import ') or l.startswith('package ') or l.strip() == '' or l.startswith('// PORT-TODO: wildcard'):
            body_start = i + 1
        else:
            break
    head = '\n'.join(lines[:body_start])
    body = '\n'.join(lines[body_start:])
    for pattern, repl in MEMBERS:
        body = re.sub(pattern, repl, body)
    for old, new in sorted(TYPES.items(), key=lambda kv: -len(kv[0])):
        if '.' in old:
            body = body.replace(old, new)
        else:
            body = re.sub(r'(?<![\w.])' + re.escape(old) + r'\b', new, body)
    return head + ('\n' if head else '') + body


def process(path):
    with open(path, encoding='utf-8') as f:
        src = f.read()
    if '// PORTED' in src:
        return False
    new = rewrite_code(rewrite_imports(src))
    if new != src:
        with open(path, 'w', encoding='utf-8') as f:
            f.write(new)
        return True
    return False


def main(paths):
    changed = 0
    for p in paths:
        if os.path.isdir(p):
            for root, _, files in os.walk(p):
                for name in files:
                    if name.endswith('.java') and process(os.path.join(root, name)):
                        changed += 1
        elif p.endswith('.java') and process(p):
            changed += 1
    print('rewrote %d files' % changed)


if __name__ == '__main__':
    main(sys.argv[1:])
